def expected_files(themes: dict[str, dict]) -> dict[Path, str]:
    factory_id = json.loads((ROOT / "profiles" / "factory.json").read_text())["defaultTheme"]
    factory, day = themes[factory_id], themes[DAY_THEME]
    widget_css = (ROOT / "desktop" / "gtk-theme" / "src" / "signal.css").read_text(encoding="utf-8")
    out: dict[Path, str] = {}
    for theme_id, doc in themes.items():
        out[ROOT / "desktop/kitty" / f"{theme_id}.conf"] = sr.render_kitty(doc)
        out[ROOT / "desktop/qt6ct/colors" / f"{theme_id}.conf"] = sr.render_qt6ct(doc)
    for tree, doc in gtk_owners(themes).items():
        base = ROOT / "desktop/gtk-theme" / tree
        css = sr.render_gtk_css(doc, widget_css, tree)
        out[base / "index.theme"] = sr.render_index_theme(doc, tree)
        out[base / "gtk-3.0/gtk.css"] = css
        out[base / "gtk-4.0/gtk.css"] = css
        out[base / "gtk-4.0/recolor.css"] = sr.render_recolor(doc, tree)
    for doc in (factory, day):
        out[ROOT / "desktop/alacritty" / f"{doc['id']}.toml"] = sr.render_alacritty(doc)
    out[ROOT / "desktop/alacritty/hornero-colors.toml"] = sr.render_alacritty(factory)
    out[ROOT / "desktop/ghostty/themes/Hornero Dynamic"] = sr.render_ghostty(factory)
    out[ROOT / "desktop/btop/themes/Hornero Dynamic.theme"] = sr.render_btop(factory)
    out[ROOT / "desktop/cava/themes/Hornero Dynamic"] = sr.render_cava(factory)
    out[ROOT / "desktop/hypr/hyprland.lua.d/smart-colors.lua"] = smart_colors_lua(factory)
    out[ROOT / "desktop/hypr/hyprland.lua.d/signal-day.lua"] = day_lua(day)
    out[ROOT / "desktop/hypr/hyprlock.conf"] = hyprlock_conf(factory)
    return out


def stale_files(expected: dict[Path, str]) -> list[Path]:
    """Generated-family files that no current theme produces any more."""
    keep = set(expected)
    stale: list[Path] = []
    families = [
        *(ROOT / "desktop/kitty").glob("*.conf"),
        *(ROOT / "desktop/qt6ct/colors").glob("*.conf"),
        *(ROOT / "desktop/alacritty").glob("*.toml"),
        *(p for p in (ROOT / "desktop/gtk-theme").glob("Hornero-*/**/*") if p.is_file()),
    ]
    hand_owned = {ROOT / "desktop/kitty/kitty.conf", ROOT / "desktop/alacritty/alacritty.toml"}
    for path in families:
        if path not in keep and path not in hand_owned:
            stale.append(path)
    return sorted(stale)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = expected_files(load_themes())
    stale = stale_files(expected)
    if args.check:
        failed = False
        for path, contents in sorted(expected.items()):
            rel = path.relative_to(ROOT)
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                print(f"APPEARANCE-FAIL: {rel} drifted (run scripts/generate-appearance.py)", file=sys.stderr)
                failed = True
        for path in stale:
            print(f"APPEARANCE-FAIL: stale generated file {path.relative_to(ROOT)}", file=sys.stderr)
            failed = True
        if failed:
            return 1
        print(f"APPEARANCE-PASS: {len(expected)} generated files match schema-v2 themes")
        return 0
    for path, contents in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents, encoding="utf-8")
    for path in stale:
        path.unlink()
    for tree in (ROOT / "desktop/gtk-theme").glob("Hornero-*"):
        if tree.is_dir() and not any(p.is_file() for p in tree.rglob("*")):
            shutil.rmtree(tree)
    print(f"generated {len(expected)} files, removed {len(stale)} stale")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
