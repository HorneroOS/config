"""generate-appearance.py - derive every shipped appearance file from v2 roles.

Single generator for the native theme files HorneroOS ships, all mapped
from profiles/themes/<id>/theme.json (schema v2, RFC 0001 §3) through
lib/hornero/signal_render.py:

  desktop/kitty/<id>.conf                     every theme
  desktop/qt6ct/colors/<id>.conf              every theme
  desktop/gtk-theme/<gtkTheme>/               every Hornero collection theme
      index.theme, gtk-3.0/gtk.css, gtk-4.0/gtk.css, gtk-4.0/recolor.css
  desktop/alacritty/<id>.toml                 factory night + day
  desktop/alacritty/hornero-colors.toml       factory fallback (night)
  desktop/ghostty/themes/Hornero Dynamic      factory fallback (night)
  desktop/btop/themes/Hornero Dynamic.theme   factory fallback (night)
  desktop/cava/themes/Hornero Dynamic         factory fallback (night)
  desktop/hypr/hyprland.lua.d/smart-colors.lua  factory borders (night)
  desktop/hypr/hyprland.lua.d/signal-day.lua    opt-in day borders
  desktop/hypr/hyprlock.conf                  factory lock (night fallback vars)

Usage: scripts/generate-appearance.py [--check]
  --check  regenerate in memory and fail on any drift or stale file.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lib" / "hornero"))

import signal_render as sr  # noqa: E402
import signal_theme as st  # noqa: E402

DAY_THEME = "hornero-signal-day"
GENERATED_BANNER = "GENERATED"


def load_themes() -> dict[str, dict]:
    themes = {}
    for path in sorted((ROOT / "profiles" / "themes").glob("*/theme.json")):
        doc = st.load(path)
        errors = st.validate(doc)
        if errors:
            raise SystemExit(f"{path}: " + "; ".join(errors))
        themes[doc["id"]] = doc
    return themes


def gtk_owners(themes: dict[str, dict]) -> dict[str, dict]:
    """Hornero collection themes own (and generate) their GTK tree."""
    owners: dict[str, dict] = {}
    for doc in themes.values():
        if doc.get("collection") in st.COLLECTIONS:
            tree = doc["gtkTheme"]
            if tree in owners:
                raise SystemExit(f"GTK tree {tree} claimed by {owners[tree]['id']} and {doc['id']}")
            owners[tree] = doc
    for doc in themes.values():
        if doc["gtkTheme"] not in owners:
            raise SystemExit(f"{doc['id']}: gtkTheme {doc['gtkTheme']} is not a generated Hornero tree")
    return owners


def smart_colors_lua(factory: dict) -> str:
    return (
        "-- Smart Colors integration for the Lua entrypoint.\n"
        f"-- GENERATED by the config generate-appearance.py from {factory['id']} (schema v2);\n"
        "-- do not hand-edit. Signal borders: 1 px matte, amber = active window.\n"
        "-- luacheck: globals hl\n"
        "\n"
        f"local factory = {sr.hyprland_table(factory)}\n"
        "\n"
        "hl.config(factory)\n"
        "\n"
        'local cache = os.getenv("HORNERO_SMART_COLORS_DIR")\n'
        'if not cache or cache == "" then\n'
        '\tlocal cache_home = os.getenv("XDG_CACHE_HOME")\n'
        '\tif not cache_home or cache_home == "" then\n'
        '\t\tcache_home = (os.getenv("HOME") or "") .. "/.cache"\n'
        "\tend\n"
        '\tcache = cache_home .. "/hornero/smart-colors"\n'
        "end\n"
        "\n"
        "-- Applying a theme renders colors-hyprland.lua from the theme's roles\n"
        "-- (lib/hornero/signal_render.py). Load it on every evaluation instead of\n"
        "-- through require's cache so a reload picks up the new theme; a missing\n"
        "-- or malformed file leaves the factory palette above in effect.\n"
        'local generated = loadfile(cache .. "/colors-hyprland.lua")\n'
        "if generated then\n"
        "\tpcall(generated)\n"
        "end\n"
    )


def day_lua(day: dict) -> str:
    return (
        f"-- Hornero Signal Day borders — opt-in fragment GENERATED from {day['id']}.\n"
        "-- Not loaded by default; uncomment its dofile line in ../hyprland.lua.\n"
        "-- Loaded after smart-colors.lua, so these values take precedence.\n"
        "-- luacheck: globals hl\n"
        "\n"
        f"hl.config({sr.hyprland_table(day)})\n"
    )


