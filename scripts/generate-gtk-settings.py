#!/usr/bin/env python3
"""Generate or verify the factory GTK settings file from Hornero theme data."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def render(root: Path) -> str:
    factory_path = root / "profiles/factory.json"
    factory = json.loads(factory_path.read_text(encoding="utf-8"))
    default_theme_id = factory["defaultTheme"]
    recipe_path = root / "profiles/themes" / default_theme_id / "theme.json"
    recipe = json.loads(recipe_path.read_text(encoding="utf-8"))

    gtk = factory["gtk"]
    expected = {
        "gtkTheme": gtk["theme"],
        "iconTheme": gtk["iconTheme"],
        "gtkPreferDark": gtk["preferDark"],
    }
    actual = {key: recipe[key] for key in expected}
    if actual != expected:
        raise ValueError(
            f"{recipe_path.relative_to(root)} does not match profiles/factory.json: "
            f"expected {expected!r}, got {actual!r}"
        )

    template_path = root / "desktop/gtk/settings.ini.in"
    template = template_path.read_text(encoding="utf-8")
    values = {
        "gtkTheme": gtk["theme"],
        "iconTheme": gtk["iconTheme"],
        "gtkPreferDark": str(gtk["preferDark"]).lower(),
    }
    for key, value in values.items():
        template = template.replace("{{ " + key + " }}", value)
    if "{{ " in template:
        raise ValueError(f"unresolved placeholder in {template_path.relative_to(root)}")
    return (
        "# Generated by scripts/generate-gtk-settings.py; edit settings.ini.in.\n"
        + template
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument(
        "--check", action="store_true", help="fail if settings.ini differs from generated output"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    output = root / "desktop/gtk/settings.ini"
    try:
        generated = render(root)
    except (KeyError, OSError, json.JSONDecodeError, ValueError) as error:
        print(f"GTKSETTINGS-FAIL: {error}", file=sys.stderr)
        return 1

    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError as error:
            print(f"GTKSETTINGS-FAIL: cannot read {output}: {error}", file=sys.stderr)
            return 1
        if current != generated:
            print(
                "GTKSETTINGS-FAIL: desktop/gtk/settings.ini differs from factory/theme output; "
                "run scripts/generate-gtk-settings.py",
                file=sys.stderr,
            )
            return 1
        print("GTKSETTINGS-PASS: settings.ini matches the factory theme recipe")
        return 0

    output.write_text(generated, encoding="utf-8")
    print(f"generated {output.relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
