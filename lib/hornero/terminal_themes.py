#!/usr/bin/env python3
"""Render one Hornero Material color scheme for supported terminal emulators."""

from __future__ import annotations

import json
import os
import re
import tempfile
from pathlib import Path

ANSI_NAMES = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
HEX = re.compile(r"^[0-9A-Fa-f]{6}$")


def _color(colors: dict[str, str], name: str) -> str:
    value = str(colors.get(name, "")).removeprefix("#")
    if not HEX.fullmatch(value):
        raise ValueError(f"scheme is missing a valid {name} color")
    return f"#{value.upper()}"


def render_kitty(colors: dict[str, str]) -> str:
    lines = [
        "# Generated by HorneroOS from the active wallpaper color scheme.",
        f"background {_color(colors, 'surface')}",
        f"foreground {_color(colors, 'onSurface')}",
        f"cursor {_color(colors, 'primary')}",
        f"cursor_text_color {_color(colors, 'onPrimaryContainer')}",
        f"selection_background {_color(colors, 'primaryContainer')}",
        f"selection_foreground {_color(colors, 'onPrimaryContainer')}",
    ]
    lines.extend(f"color{index} {_color(colors, f'term{index}')}" for index in range(16))
    return "\n".join(lines) + "\n"


def render_alacritty(colors: dict[str, str]) -> str:
    lines = [
        "# Generated by HorneroOS from the active wallpaper color scheme.",
        "[colors.primary]",
        f'background = "{_color(colors, "surface")}"',
        f'foreground = "{_color(colors, "onSurface")}"',
        "",
        "[colors.cursor]",
        f'cursor = "{_color(colors, "primary")}"',
        f'text = "{_color(colors, "onPrimaryContainer")}"',
        "",
        "[colors.selection]",
        f'background = "{_color(colors, "primaryContainer")}"',
        f'text = "{_color(colors, "onPrimaryContainer")}"',
    ]
    for group, start in (("normal", 0), ("bright", 8)):
        lines.extend(("", f"[colors.{group}]"))
        lines.extend(
            f'{name} = "{_color(colors, f"term{start + index}")}"'
            for index, name in enumerate(ANSI_NAMES)
        )
    return "\n".join(lines) + "\n"


def render_ghostty(colors: dict[str, str]) -> str:
    lines = ["# Generated by HorneroOS from the active wallpaper color scheme."]
    lines.extend(f"palette = {index}={_color(colors, f'term{index}')}" for index in range(16))
    lines.extend(
        (
            f"background = {_color(colors, 'surface')}",
            f"foreground = {_color(colors, 'onSurface')}",
            f"cursor-color = {_color(colors, 'primary')}",
            f"cursor-text = {_color(colors, 'onPrimaryContainer')}",
            f"selection-background = {_color(colors, 'primaryContainer')}",
            f"selection-foreground = {_color(colors, 'onPrimaryContainer')}",
        )
    )
    return "\n".join(lines) + "\n"


def _atomic_write(path: str | Path, contents: str) -> None:
    destination = Path(path).expanduser()
    destination.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{destination.name}.", dir=destination.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(contents)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, destination)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def render_scheme(
    colors: dict[str, str],
    *,
    kitty_output: str | Path | None = None,
    alacritty_output: str | Path | None = None,
    ghostty_output: str | Path | None = None,
) -> dict[str, str]:
    """Validate a scheme fully, then atomically write the requested formats."""
    requested = {
        str(path): renderer(colors)
        for path, renderer in (
            (kitty_output, render_kitty),
            (alacritty_output, render_alacritty),
            (ghostty_output, render_ghostty),
        )
        if path is not None
    }
    for path, contents in requested.items():
        _atomic_write(path, contents)
    return requested


def render_scheme_file(
    scheme_file: str | Path,
    *,
    kitty_output: str | Path | None = None,
    alacritty_output: str | Path | None = None,
    ghostty_output: str | Path | None = None,
) -> dict[str, str]:
    scheme = json.loads(Path(scheme_file).expanduser().read_text(encoding="utf-8"))
    colors = scheme.get("colours")
    if not isinstance(colors, dict):
        raise ValueError("scheme file must contain an object at 'colours'")
    return render_scheme(
        colors,
        kitty_output=kitty_output,
        alacritty_output=alacritty_output,
        ghostty_output=ghostty_output,
    )


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scheme", required=True, help="Generated Hornero M3 scheme JSON")
    parser.add_argument("--kitty-output")
    parser.add_argument("--alacritty-output")
    parser.add_argument("--ghostty-output")
    args = parser.parse_args()
    if not any((args.kitty_output, args.alacritty_output, args.ghostty_output)):
        parser.error("at least one terminal output path is required")
    try:
        outputs = render_scheme_file(
            args.scheme,
            kitty_output=args.kitty_output,
            alacritty_output=args.alacritty_output,
            ghostty_output=args.ghostty_output,
        )
    except (OSError, ValueError, json.JSONDecodeError) as error:
        parser.exit(1, f"terminal colors: {error}\n")
    for path in outputs:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
